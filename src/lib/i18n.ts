export type Cheie = keyof (typeof t)['ro'];

export function traduceri(lang: Limba) {
  return (cheie: Cheie, inlocuiri?: Record<string, string>): string => {
    let s: string = t[lang][cheie] ?? t.ro[cheie] ?? cheie;
    if (inlocuiri) {
      for (const [k, v] of Object.entries(inlocuiri)) s = s.replace(`{${k}}`, v);
    }
    return s;
  };
}
